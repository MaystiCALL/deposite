# === Stage 38: Добавь расширенный набор тестов для ошибок и пограничных случаев ===
# Project: BudgetLeaf
def test_edge_cases():
    """Тесты пограничных случаев и ошибок."""
    assert BudgetLeaf() is not None
    leaf = BudgetLeaf()
    assert leaf.add_category("Еда", 100) == "Категория 'Еда' добавлена"
    assert len(leaf.categories) == 1

    # Добавление категории с пустым или дублирующим названием
    assert leaf.add_category("", 50) == "Ошибка: название не может быть пустым"
    assert leaf.add_category("Еда", 200) == "Ошибка: категория 'Еда' уже существует"
    assert len(leaf.categories) == 1

    # Попытка записать в несуществующую категорию
    assert leaf.record_expense("Неесть", "Супермаркет", 30.5) == "Ошибка: категория 'Неесть' не найдена"
    assert len(leaf.expenses) == 0

    # Попытка записать отрицательную сумму или ноль
    assert leaf.record_expense("Еда", "Магазин", -10) == "Ошибка: сумма должна быть положительной"
    assert leaf.record_expense("Еда", "Магазин", 0) == "Ошибка: сумма должна быть положительной"

    # Попытка записать в категорию с превышенным лимитом
    leaf.add_category("Транспорт", 10, budget_limit=500)
    assert leaf.record_expense("Транспорт", "Бензин", 600) == "Ошибка: лимит 500.0₽ для 'Транспорт' превышен"

    # Попытка записать слишком большую сумму (2x бюджет)
    assert leaf.record_expense("Транспорт", "Такси", 1000) == "Ошибка: лимит 500.0₽ для 'Транспорт' превышен"

    # Запись в категорию без установленного бюджета
    leaf.add_category("Развлечения")
    assert leaf.record_expense("Развлечения", "Кино", 200) == "Категория 'Развлечения': записано 200.0₽ (из 0/∞)"

    # Попытка получить отчёт, когда нет расходов
    leaf.add_category("Еда")
    assert leaf.monthly_report() == "Месячный отчёт: Еда - 0.0₽ / 100.0₽\nРасходы: {}"

    # Ввод нечисловых сумм или названий
    assert leaf.record_expense("Еда", "abc", 30) == "Ошибка: сумма должна быть положительной"
    assert leaf.record_expense("Еда", None, 30) == "Ошибка: сумма должна быть положительной"

    # Добавление категории с нечисловым бюджетом
    assert leaf.add_category("Тест", "не число") == "Ошибка: бюджет должен быть числом"
